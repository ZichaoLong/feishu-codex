@dataclass(slots=True, frozen=True)
class _ClientDocument:
    """One live browser-document incarnation for a registered Web client.

    The Gateway issues ``client_id`` and only lets its current authenticated
    session resume it during disconnect grace.  The document token does not
    survive a reload: it is generated by the Gateway and retained only by the
    current JavaScript document.  A duplicated tab may copy sessionStorage's
    resume hint, but it cannot silently share a live document's authority.
    """

    session_token: str
    incarnation_id: str
    document_token: str
    document_receipt: str


