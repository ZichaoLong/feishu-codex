    async def _handle_prompt(self, request: web.Request) -> web.Response:
        client_id, _request_document_receipt = self._required_client_document(request)
        body = await request_decoder.decode_json_object(request)
        expected_fields = {
            "text",
            "attachment_ids",
            "mutation_id",
            "source_scope_generation",
            "source_attachment_scope",
            "source_composer_scope_id",
        }
        if set(body) != expected_fields:
            raise WebRuntimeError(
                "A prompt submission requires one exact single-request body.",
                code="invalid_prompt",
                status=400,
            )
        mutation_id = body.get("mutation_id")
        if not is_web_mutation_id(mutation_id):
            raise WebRuntimeError(
                "Prompt mutation_id must be one canonical UUID.",
                code="invalid_mutation_id",
                status=400,
            )
        text = body.get("text")
        source_attachment_scope = body.get("source_attachment_scope")
        source_composer_scope_id = body.get("source_composer_scope_id")
        if not isinstance(text, str):
            raise WebRuntimeError(
                "Prompt text must be a string.",
                code="invalid_prompt",
                status=400,
            )
        if not all(
            request_decoder.is_exact_text(value)
            for value in (source_attachment_scope, source_composer_scope_id)
        ):
            raise WebRuntimeError(
                "Prompt source-scope fields must be exact non-empty strings.",
                code="invalid_submission_scope",
                status=400,
            )
        return web.json_response(
            await self._staged_document_request_to_thread(
                self._ports.prepare_prompt,
                request,
                client_id,
                request.match_info["thread_id"],
                execute=self._ports.run_prepared_prompt,
                transactions=self._prompt_transactions,
                text=text,
                attachment_ids=request_decoder.decode_attachment_ids(body),
                mutation_id=mutation_id,
                source_scope_generation=request_decoder.decode_safe_integer_field(
                    body,
                    "source_scope_generation",
                    positive=True,
                ),
                source_attachment_scope=source_attachment_scope,
                source_composer_scope_id=source_composer_scope_id,
            )
        )

