class WebGatewayShutdownError(RuntimeError):
    """The Gateway could not prove that its event-loop thread exited.

    ``stop()`` is deliberately retryable.  Until a later call establishes the
    thread barrier, the Gateway retains its thread, loop, and endpoint handles
    so the service lifecycle cannot mistake an incomplete stop for closure.
    """


