    async def _handle_attachment_upload(self, request: web.Request) -> web.Response:
        client_id = self._required_client_id(request)
        if not request.content_type.startswith("multipart/"):
            raise WebRuntimeError(
                "Attachment upload must use multipart/form-data.",
                code="invalid_attachment",
            )
        reader = await request.multipart()
        thread_id = ""
        cwd = ""
        scope_generation = 0
        display_name = ""
        media_type = "application/octet-stream"
        content = bytearray()
        file_seen = False
        while True:
            field = await reader.next()
            if field is None:
                break
            if field.name == "file":
                if file_seen:
                    raise WebRuntimeError(
                        "Only one file can be uploaded per request.",
                        code="invalid_attachment",
                    )
                file_seen = True
                display_name = str(field.filename or "attachment")
                media_type = str(
                    field.headers.get("Content-Type", "") or "application/octet-stream"
                )
                while True:
                    chunk = await field.read_chunk(size=256 * 1024)
                    if not chunk:
                        break
                    content.extend(chunk)
                    if len(content) > _MAX_ATTACHMENT_BYTES:
                        raise WebRuntimeError(
                            f"Attachment exceeds the {_MAX_ATTACHMENT_BYTES}-byte limit.",
                            code="invalid_attachment",
                            status=413,
                        )
                continue
            value = (await field.text()).strip()
            if field.name == "thread_id":
                thread_id = value
            elif field.name == "cwd":
                cwd = value
            elif field.name == "scope_generation":
                try:
                    scope_generation = int(value)
                except ValueError as exc:
                    raise WebRuntimeError(
                        "Attachment scope generation must be an integer.",
                        code="invalid_attachment_scope",
                    ) from exc
        if not file_seen:
            raise WebRuntimeError(
                "Attachment upload is missing file content.", code="invalid_attachment"
            )
        result = await self._document_request_to_thread(
            self._ports.stage_attachment,
            request,
            client_id,
            thread_id=thread_id,
            cwd=cwd,
            scope_generation=scope_generation,
            display_name=display_name,
            media_type=media_type,
            content=bytes(content),
        )
        return web.json_response(result)

    async def _handle_attachment_download(
        self, request: web.Request
    ) -> web.StreamResponse:
        download = await asyncio.to_thread(
            self._ports.attachment_download,
            request.match_info["attachment_id"],
        )
        record = download.record
        media_type = str(record.media_type or "").lower()
        # Keep this narrow even if a port implementation regresses: this
        # cookie-authenticated route is a controlled image loader, not a
        # generic attachment download endpoint.
        if media_type not in _SAFE_INLINE_IMAGE_TYPES:
            raise WebRuntimeError(
                "Only verified image attachments can be rendered in Focus Web.",
                code="attachment_preview_unavailable",
                status=404,
            )
        response = web.Response(body=download.content)
        response.content_type = record.media_type or "application/octet-stream"
        response.headers["Content-Disposition"] = (
            f"inline; filename*=UTF-8''{quote(str(record.display_name), safe='')}"
        )
        response.headers["Cache-Control"] = "private, max-age=300"
        return response

