    async def _handle_events(self, request: web.Request) -> web.StreamResponse:
        session = self._request_admission.session(request)
        client_id = self._query_client_id(request)
        csrf_token = str(request.query.get("csrf", "") or "").strip()
        self._request_admission.validate_websocket_csrf(session, csrf_token)
        self._request_admission.validate_origin(request)
        socket = web.WebSocketResponse(heartbeat=30.0, max_msg_size=1024 * 1024)
        sender_state = _SocketSenderState(
            queue=asyncio.Queue(maxsize=max(int(self._config.event_queue_limit), 1)),
        )
        external_reservation = False
        if session.audience.kind == "external":
            self._reserve_external_socket(session.session_token)
            external_reservation = True
        admitted = False
        rejection: WebRuntimeError | None = None
        try:
            await socket.prepare(request)
            async with self._client_operation(client_id):
                try:
                    # ``prepare`` is an await boundary. Registration may have
                    # rotated this document while the HTTP upgrade was in
                    # flight, so exact capability admission is rechecked
                    # before this socket becomes lifecycle evidence.
                    self._query_client_id(request)
                except WebRuntimeError as exc:
                    rejection = exc
                else:
                    disconnect_task = self._disconnect_tasks.pop(client_id, None)
                    if disconnect_task is not None:
                        disconnect_task.cancel()
                    self._socket_senders[socket] = sender_state
                    self._websockets.setdefault(client_id, set()).add(socket)
                    if external_reservation:
                        self._release_external_socket_reservation(session.session_token)
                        external_reservation = False
                    self._session_sockets.setdefault(
                        session.session_token,
                        set(),
                    ).add(socket)
                    self._socket_clients[socket] = client_id
                    admitted = True
                    await asyncio.to_thread(self._ports.client_connected, client_id)
            if rejection is not None:
                await socket.close(
                    code=4001 if rejection.status == 401 else 4003,
                    message=(
                        b"Focus Web session expired"
                        if rejection.status == 401
                        else b"Focus Web document was replaced"
                    ),
                )
                return socket
            await socket.send_json(
                {
                    "type": require_focus_web_event_type("hello"),
                    **self._projection.coordinates(),
                }
            )
            sender_state.task = asyncio.create_task(
                self._run_socket_sender(socket, sender_state)
            )
            async for message in socket:
                if message.type == WSMsgType.TEXT and message.data == "ping":
                    await socket.send_str("pong")
                elif message.type == WSMsgType.ERROR:
                    break
        finally:
            if external_reservation:
                self._release_external_socket_reservation(session.session_token)
            if admitted:
                async with self._client_operation(client_id):
                    self._remove_socket_sender(socket)
                    self._socket_clients.pop(socket, None)
                    session_group = self._session_sockets.get(session.session_token)
                    if session_group is not None:
                        session_group.discard(socket)
                        if not session_group:
                            self._session_sockets.pop(session.session_token, None)
                            self._maybe_cancel_session_expiry(session.session_token)
                    group = self._websockets.get(client_id)
                    if group is not None:
                        group.discard(socket)
                        if not group:
                            self._websockets.pop(client_id, None)
                            await asyncio.to_thread(
                                self._ports.client_transport_disconnected,
                                client_id,
                            )
                            self._schedule_disconnect_after_grace(client_id)
        return socket

    async def _expire_session_after(self, session: WebAuthSession) -> None:
        try:
            await asyncio.sleep(max(session.expires_at - time.time(), 0.0))
            self._auth.revoke(session.session_token)
            await self._close_session_sockets(
                session.session_token,
                event_type="session_expired",
                close_message=b"Focus Web session expired",
            )
        except asyncio.CancelledError:
            return
        finally:
            current = self._session_expiry_tasks.get(session.session_token)
            if current is asyncio.current_task():
                self._session_expiry_tasks.pop(session.session_token, None)

    async def _close_session_sockets(
        self,
        session_token: str,
        *,
        event_type: str,
        close_message: bytes,
    ) -> None:
        event_type = require_focus_web_event_type(event_type)
        expiry_task = self._session_expiry_tasks.pop(session_token, None)
        if expiry_task is not None and expiry_task is not asyncio.current_task():
            expiry_task.cancel()
        sockets = tuple(self._session_sockets.pop(session_token, set()))
        affected_clients = set(self._session_clients.pop(session_token, set()))
        affected_clients.update(
            client_id
            for client_id, document in self._client_documents.items()
            if document.session_token == session_token
        )
        for socket in sockets:
            self._remove_socket_sender(socket)
            client_id = self._socket_clients.pop(socket, "")
            if client_id:
                affected_clients.add(client_id)
                group = self._websockets.get(client_id)
                if group is not None:
                    group.discard(socket)
                    if not group:
                        self._websockets.pop(client_id, None)
            if not socket.closed:
                try:
                    await socket.send_json(
                        {"type": event_type, **self._projection.coordinates()}
                    )
                except Exception:
                    logger.debug(
                        "Focus Web session close event delivery failed", exc_info=True
                    )
                await socket.close(code=4001, message=close_message)
        for client_id in sorted(affected_clients):
            if self._client_sessions.get(client_id) == session_token:
                self._client_sessions.pop(client_id, None)
            document = self._client_documents.get(client_id)
            if document is not None and document.session_token == session_token:
                self._client_documents.pop(client_id, None)
            if client_id in self._websockets:
                continue
            disconnect_task = self._disconnect_tasks.pop(client_id, None)
            if disconnect_task is not None:
                disconnect_task.cancel()
            async with self._client_operation(client_id):
                await asyncio.to_thread(self._ports.client_disconnected, client_id)

    async def _disconnect_after_grace(
        self,
        client_id: str,
        expected_document: _ClientDocument | None,
    ) -> None:
        try:
            await asyncio.sleep(max(float(self._config.disconnect_grace_seconds), 0.0))
            async with self._client_operation(client_id):
                if client_id in self._websockets:
                    return
                if (
                    expected_document is not None
                    and self._client_documents.get(client_id) is not expected_document
                ):
                    return
                await asyncio.to_thread(self._ports.client_disconnected, client_id)
                if (
                    expected_document is None
                    or self._client_documents.get(client_id) is expected_document
                ):
                    self._forget_client_session(client_id)
        except asyncio.CancelledError:
            return
        finally:
            current = self._disconnect_tasks.get(client_id)
            if current is asyncio.current_task():
                self._disconnect_tasks.pop(client_id, None)
            self._maybe_release_client_operation_lock(client_id)

    def _schedule_disconnect_after_grace(
        self,
        client_id: str,
        *,
        initial: bool = False,
    ) -> None:
        """Bound a registered document that has no active event socket.

        Registration happens before the SPA opens its WebSocket.  Giving that
        short window the same bounded grace avoids a stale, HTTP-only document
        keeping a resume hint (or a writer identity) alive until session expiry.
        A connected socket always cancels the task in ``_handle_events``.
        """

        # ``0`` deliberately means no reconnect grace after a socket closes.
        # Do not turn that setting into a race between initial registration and
        # the SPA's first ``/api/meta`` / WebSocket handshake.
        if initial and float(self._config.disconnect_grace_seconds) <= 0:
            return
        if client_id in self._websockets or client_id in self._disconnect_tasks:
            return
        expected_document = self._client_documents.get(client_id)
        self._disconnect_tasks[client_id] = asyncio.create_task(
            self._disconnect_after_grace(client_id, expected_document)
        )

    async def _handle_static(self, request: web.Request) -> web.StreamResponse:
        path = str(request.match_info.get("path", "") or "").strip("/")
        static_dir = self._static_dir().resolve()
        target = (static_dir / (path or "index.html")).resolve()
        try:
            target.relative_to(static_dir)
        except ValueError:
            raise web.HTTPNotFound()
        if not target.is_file():
            if "." in pathlib.PurePosixPath(path).name:
                raise web.HTTPNotFound()
            target = static_dir / "index.html"
        content_type, _encoding = mimetypes.guess_type(target.name)
        response = web.FileResponse(target)
        if content_type:
            response.content_type = content_type
        if target.name in _STATIC_NO_STORE_FILENAMES:
            response.headers["Cache-Control"] = "no-store"
        else:
            response.headers["Cache-Control"] = "public, max-age=31536000, immutable"
        return response

    def _on_projection_event(self, event: dict[str, Any]) -> None:
        loop = self._loop
        if loop is None or not loop.is_running():
            return
        payload = dict(event)
        loop.call_soon_threadsafe(self._enqueue_projection_event, payload)

    async def _document_request_to_thread(
        self,
        function: Callable[..., Any],
        request: web.Request,
        lock_client_id: str,
        *args: Any,
        pass_client_id: bool = True,
        **kwargs: Any,
    ) -> Any:
        """Dispatch one exact document request at its lifecycle linearization point.

        Parsing JSON or multipart bodies is an await boundary, and an already
        queued request may also wait behind another client operation.  Recheck
        the request's exact token and active session while holding the same
        lock as document reissue, socket admission, and retirement.  Stable
        client id alone is never authority to dispatch a replaced document.
        """

        async with self._client_operation(lock_client_id) as normalized_client_id:
            verified_client_id = self._required_client_id(request)
            if verified_client_id != normalized_client_id:
                raise WebRuntimeError(
                    "This browser document no longer owns the requested client id.",
                    code="document_replaced",
                    status=409,
                )
            call_args = (normalized_client_id, *args) if pass_client_id else args
            return await asyncio.to_thread(function, *call_args, **kwargs)

    async def _staged_document_request_to_thread(
        self,
        prepare: Callable[..., Any],
        request: web.Request,
        lock_client_id: str,
        *args: Any,
        pass_client_id: bool = True,
        execute: Callable[[Any], Any] | None = None,
        transactions: WebGatewayExternalTransactionRunner | None = None,
        **kwargs: Any,
    ) -> Any:
        """Prepare under the document lock, then release it before slow I/O.

        The independent prepare task owns the lock through worker completion.
        A cancelled handler therefore cannot let document replacement overtake
        a still-running prepare callback; its exact receipt is abandoned when
        that task eventually returns instead.
        """

        async def prepare_under_document_lock() -> Any:
            async with self._client_operation(lock_client_id) as normalized_client_id:
                verified_client_id = self._required_client_id(request)
                if verified_client_id != normalized_client_id:
                    raise WebRuntimeError(
                        "This browser document no longer owns the requested client id.",
                        code="document_replaced",
                        status=409,
                    )
                call_args = (
                    (normalized_client_id, *args) if pass_client_id else args
                )
                return await asyncio.to_thread(prepare, *call_args, **kwargs)

        transaction_runner = transactions or self._external_transactions
        prepared = await transaction_runner.prepare_async(
            prepare_under_document_lock
        )
        return await transaction_runner.execute(
            prepared,
            execute or self._ports.run_prepared_thread_read,
        )

    @asynccontextmanager
    async def _client_operation(self, client_id: str) -> AsyncIterator[str]:
        """Linearize one client's HTTP, socket, registration, and retirement."""

        normalized_client_id = str(client_id or "").strip()
        if not normalized_client_id:
            raise WebRuntimeError(
                "A valid browser client id is required.",
                code="invalid_client",
            )
        lock = self._client_operation_locks.setdefault(
            normalized_client_id,
            asyncio.Lock(),
        )
        self._client_operation_lock_users[normalized_client_id] = (
            self._client_operation_lock_users.get(normalized_client_id, 0) + 1
        )
        try:
            async with lock:
                yield normalized_client_id
        finally:
            users = self._client_operation_lock_users.get(normalized_client_id, 1) - 1
            if users > 0:
                self._client_operation_lock_users[normalized_client_id] = users
            else:
                self._client_operation_lock_users.pop(normalized_client_id, None)
            self._maybe_release_client_operation_lock(normalized_client_id)

    def _maybe_release_client_operation_lock(self, client_id: str) -> None:
        """Drop event-loop bookkeeping after a document leaves the Gateway."""

        if self._client_operation_lock_users.get(client_id, 0) > 0:
            return
        if (
            client_id not in self._client_sessions
            and client_id not in self._websockets
            and client_id not in self._disconnect_tasks
        ):
            self._client_operation_locks.pop(client_id, None)

    def _enqueue_projection_event(self, event: dict[str, Any]) -> None:
        for socket, state in tuple(self._socket_senders.items()):
            if socket.closed or state.overflowed:
                continue
            try:
                state.queue.put_nowait(dict(event))
            except asyncio.QueueFull:
                while True:
                    try:
                        state.queue.get_nowait()
                    except asyncio.QueueEmpty:
                        break
                state.overflowed = True
                invalidation = {
                    **event,
                    "type": require_focus_web_event_type("projection_invalidated"),
                    "thread_id": "",
                    "reason": "socket_backpressure",
                    "detail": {"reload": True},
                }
                state.queue.put_nowait(invalidation)

    async def _run_socket_sender(
        self,
        socket: web.WebSocketResponse,
        state: _SocketSenderState,
    ) -> None:
        try:
            while not socket.closed:
                event = await state.queue.get()
                await socket.send_json(event)
                if event.get("type") == "projection_invalidated":
                    state.overflowed = False
        except asyncio.CancelledError:
            return
        except Exception:
            logger.debug("Focus Web event delivery failed", exc_info=True)
            if not socket.closed:
                await socket.close(
                    code=1011, message=b"Focus Web event delivery failed"
                )

    def _remove_socket_sender(self, socket: web.WebSocketResponse) -> None:
        state = self._socket_senders.pop(socket, None)
        if state is None or state.task is None:
            return
        state.task.cancel()

    def _handle_bootstrap_rotated(self, token: str) -> None:
        if self._endpoint:
            self._save_runtime(bootstrap_token=token)

    def _save_runtime(self, *, bootstrap_token: str | None = None) -> None:
        self._runtime_store.save(
            endpoint=self._endpoint,
            bootstrap_token=bootstrap_token or self._auth.bootstrap_token,
            owner_pid=os.getpid(),
            started_at=self._started_at or time.time(),
        )

    def _clear_runtime_store_safely(self) -> None:
        """Best-effort cleanup that never hides a startup or shutdown error.

        An invalid discovery record cannot be ownership-checked, so the store
        deliberately rejects it instead of deleting it.  Gateway lifecycle
        cleanup must preserve that fail-closed evidence without replacing the
        primary lifecycle result (or preventing ``_ready`` from being set).
        """

        try:
            self._runtime_store.clear(owner_pid=os.getpid())
        except Exception:
            logger.exception(
                "无法安全清理 Focus Web Gateway runtime discovery；保留文件供诊断"
            )

    def _static_dir(self) -> pathlib.Path:
        if self._config.static_dir is not None:
            return pathlib.Path(self._config.static_dir)
        return pathlib.Path(web_assets.__file__).resolve().parent / "dist"

    def _optional_client_id(self, request: web.Request) -> str:
        client_id = str(request.headers.get(_CLIENT_HEADER, "") or "").strip()
        document_token = str(request.headers.get(_DOCUMENT_HEADER, "") or "").strip()
        if not client_id and not document_token:
            return ""
        if not client_id or not document_token:
            raise WebRuntimeError(
                "This browser document must be registered before it can use Focus Web.",
                code="document_unregistered",
                status=409,
            )
        return self._verified_document_client(
            self._request_admission.session(request),
            client_id=client_id,
            document_token=document_token,
        )

    def _required_client_id(self, request: web.Request) -> str:
        value = self._optional_client_id(request)
        if not value:
            raise WebRuntimeError("Missing browser client id.", code="invalid_client")
        return value

    def _required_client_document(self, request: web.Request) -> tuple[str, str]:
        client_id = self._required_client_id(request)
        document = self._client_documents.get(client_id)
        if document is None:
            raise WebRuntimeError(
                "This browser document is no longer registered.",
                code="document_replaced",
                status=409,
            )
        return client_id, document.document_receipt

    def _query_client_id(self, request: web.Request) -> str:
        client_id = str(request.query.get("client", "") or "").strip()
        document_token = str(request.query.get("document", "") or "").strip()
        if not client_id or not document_token:
            raise web.HTTPBadRequest(text="Missing browser document identity.")
        return self._verified_document_client(
            self._request_admission.session(request),
            client_id=client_id,
            document_token=document_token,
        )

    @staticmethod
    def _new_client_id() -> str:
        return f"web-{secrets.token_urlsafe(18)}"

    def _register_client_document(
        self,
        session: WebAuthSession,
        *,
        claimed_client_id: str,
        incarnation_id: str,
    ) -> tuple[str, _ClientDocument, bool, bool]:
        """Bind one memory-only document capability to a resumable client id.

        A live socket is the observable proof that the previous document is
        still present.  In that case a copied sessionStorage hint receives a
        new identity.  Once the old socket is gone, the same authenticated
        session may use its still-registered hint during disconnect grace; the
        old document token is rotated so it cannot continue to act. Once grace
        removes that registration, the hint is intentionally not adopted
        again: a copied browser value cannot recreate a dead document
        capability. Main-turn ownership is checked independently by the exact
        interaction lease.
        """

        existing = (
            self._client_documents.get(claimed_client_id) if claimed_client_id else None
        )
        duplicate = False
        if existing is not None:
            if (
                existing.session_token == session.session_token
                and existing.incarnation_id == incarnation_id
            ):
                self._bind_client_session(session, claimed_client_id)
                return claimed_client_id, existing, False, False
            if existing.session_token != session.session_token or bool(
                self._websockets.get(claimed_client_id)
            ):
                duplicate = True

        client_id = self._new_client_id()
        while client_id in self._client_documents or client_id in self._client_sessions:
            client_id = self._new_client_id()
        if existing is not None and not duplicate:
            client_id = claimed_client_id

        document_token = secrets.token_urlsafe(32)
        document = _ClientDocument(
            session_token=session.session_token,
            incarnation_id=incarnation_id,
            document_token=document_token,
            document_receipt=hashlib.sha256(document_token.encode("ascii")).hexdigest(),
        )
        self._client_documents[client_id] = document
        self._bind_client_session(session, client_id)
        reissued = bool(
            existing is not None and not duplicate and client_id == claimed_client_id
        )
        return client_id, document, duplicate, reissued

    def _verified_document_client(
        self,
        session: WebAuthSession,
        *,
        client_id: str,
        document_token: str,
    ) -> str:
        self._require_active_session(session)
        normalized_client_id = request_decoder.decode_client_id_hint(client_id)
        normalized_document_token = str(document_token or "").strip()
        if (
            not normalized_client_id
            or not normalized_document_token
            or len(normalized_document_token) > 256
        ):
            raise WebRuntimeError(
                "This browser document must be registered before it can use Focus Web.",
                code="document_unregistered",
                status=409,
            )
        document = self._client_documents.get(normalized_client_id)
        if (
            document is None
            or document.session_token != session.session_token
            or not secrets.compare_digest(
                document.document_token, normalized_document_token
            )
        ):
            raise WebRuntimeError(
                "This browser document was replaced or is no longer registered.",
                code="document_replaced",
                status=409,
            )
        self._bind_client_session(session, normalized_client_id)
        return normalized_client_id

    def _require_active_session(self, session: WebAuthSession) -> None:
        if self._auth.authenticate(session.session_token) is None:
            raise WebRuntimeError(
                "This Focus Web session is no longer active.",
                code="unauthorized",
                status=401,
            )

    def _reserve_external_socket(self, session_token: str) -> None:
        pending = self._external_socket_reservations.get(session_token, 0)
        session_count = len(self._session_sockets.get(session_token, ())) + pending
        total_count = sum(map(len, self._session_sockets.values())) + sum(
            self._external_socket_reservations.values()
        )
        if (
            session_count >= _MAX_EXTERNAL_SESSION_SOCKETS
            or total_count >= _MAX_EXTERNAL_SOCKETS
        ):
            raise web.HTTPTooManyRequests(
                text="Focus Web external socket limit reached."
            )
        self._external_socket_reservations[session_token] = pending + 1

    def _release_external_socket_reservation(self, session_token: str) -> None:
        pending = self._external_socket_reservations.get(session_token, 0)
        if pending <= 1:
            self._external_socket_reservations.pop(session_token, None)
        else:
            self._external_socket_reservations[session_token] = pending - 1

    def _bind_client_session(self, session: WebAuthSession, client_id: str) -> None:
        self._client_sessions[client_id] = session.session_token
        self._session_clients.setdefault(session.session_token, set()).add(client_id)
        if session.session_token not in self._session_expiry_tasks:
            self._session_expiry_tasks[session.session_token] = asyncio.create_task(
                self._expire_session_after(session)
            )

    def _forget_client_session(self, client_id: str) -> None:
        session_token = self._client_sessions.pop(client_id, "")
        if not session_token:
            return
        document = self._client_documents.get(client_id)
        if document is not None and document.session_token == session_token:
            self._client_documents.pop(client_id, None)
        clients = self._session_clients.get(session_token)
        if clients is not None:
            clients.discard(client_id)
            if not clients:
                self._session_clients.pop(session_token, None)
        self._maybe_cancel_session_expiry(session_token)

    def _maybe_cancel_session_expiry(self, session_token: str) -> None:
        if self._session_sockets.get(session_token) or self._session_clients.get(
            session_token
        ):
            return
        expiry_task = self._session_expiry_tasks.pop(session_token, None)
        if expiry_task is not None and expiry_task is not asyncio.current_task():
            expiry_task.cancel()
